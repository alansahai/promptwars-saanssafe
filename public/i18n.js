/** @type {string} Current active language */
let _lang = "en";

/**
 * Set the active UI language.
 * @param {string} lang - Language code: 'en', 'hi', or 'ta'.
 */
export function setLang(lang) {
  if (STRINGS[lang]) _lang = lang;
}

/**
 * Translate a string key into the current language.
 * Falls back to English if key not found in current language.
 * @param {string} key
 * @returns {string}
 */
export function t(key) {
  return STRINGS[_lang]?.[key] ?? STRINGS["en"]?.[key] ?? key;
}

/**
 * Apply all data-i18n translations to the current document.
 * Call this whenever language changes.
 */
export function applyTranslations() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key) el.textContent = t(key);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key) el.setAttribute("placeholder", t(key));
  });
  // Update html lang attribute
  document.documentElement.lang = _lang;
}

/** Get the current active language code. */
export function getLang() {
  return _lang;
}
